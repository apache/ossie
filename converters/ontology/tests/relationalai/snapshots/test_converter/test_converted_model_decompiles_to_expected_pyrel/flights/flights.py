m.where(airport := Airport.lookup(code=database_schema_runways.AIRPORT_CODE)).define(Runway.new(designator=database_schema_runways.DESIGNATOR, airport=airport))
m.where(runway := Runway.to_identity(designator=database_schema_runways.DESIGNATOR, airport=airport, unsafe=True), airport := Airport.lookup(code=database_schema_runways.AIRPORT_CODE)).define(runway.length(RunwayLength(database_schema_runways.LENGTH)))
m.where(runway := Runway.to_identity(designator=database_schema_runways.DESIGNATOR, airport=airport, unsafe=True), airport := Airport.lookup(code=database_schema_runways.AIRPORT_CODE)).define(runway.geometry(RunwayGeometry(database_schema_runways.SHAPE)))
m.define(Manufacturer.new(name=database_schema_aircraft.MANUFACTURER))
