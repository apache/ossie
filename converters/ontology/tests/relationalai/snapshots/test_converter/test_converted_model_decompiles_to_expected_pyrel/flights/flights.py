m.define(Aircraft.new(tailnum=database_schema_aircraft.TAIL_NR))
m.where(aircraft := Aircraft.to_identity(tailnum=database_schema_aircraft.TAIL_NR, unsafe=True)).define(aircraft.serial_number(SerialNr(database_schema_aircraft.SERIAL_NR)))
m.where(aircraft := Aircraft.to_identity(tailnum=database_schema_aircraft.TAIL_NR, unsafe=True)).define(aircraft.name(database_schema_aircraft.NAME))
m.where(aircraft := Aircraft.to_identity(tailnum=database_schema_aircraft.TAIL_NR, unsafe=True)).define(aircraft.number_of_seats(database_schema_aircraft.NR_SEATS))
m.where(aircraft := Aircraft.to_identity(tailnum=database_schema_aircraft.TAIL_NR, unsafe=True), manufacturer := Manufacturer.lookup(name=database_schema_aircraft.MANUFACTURER), model := Model_2.lookup(name=database_schema_aircraft.MODEL, manufacturer=manufacturer)).define(aircraft.model(model))
